# pandas 라이브러리를 pd라는 이름으로 불러온다
import pandas as pd

# 누가 봐도 가짜인 게임명 3개와 숫자 가격으로 표(DataFrame)를 만든다
df = pd.DataFrame({
    # 게임명 열: 실제 게임이 아닌 가짜 이름
    "게임명": ["가짜게임A", "테스트게임B", "예시게임C"],
    # 가격 열: 정수 숫자(원)
    "가격": [10000, 25000, 38000],
})

# 표 위에 안내 문구를 출력한다
print("환경 확인용 가상 예시")
# 표 전체를 출력한다
print(df)
# 표의 (행 수, 열 수)를 출력한다
print(df.shape)
